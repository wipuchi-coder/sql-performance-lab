BEGIN;
CREATE SCHEMA IF NOT EXISTS fintech;
CREATE TABLE IF NOT EXISTS fintech.currency (
    code text PRIMARY KEY CHECK (code ~ '^[A-Z]{3}$')
);
CREATE TABLE IF NOT EXISTS fintech.customer (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    full_name text NOT NULL
);
CREATE TABLE IF NOT EXISTS fintech.account (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES fintech.customer,
    currency_code text NOT NULL REFERENCES fintech.currency,
    balance numeric(18,2) NOT NULL DEFAULT 0 CHECK (balance >= 0 AND balance <> 'NaN')
);
CREATE INDEX IF NOT EXISTS account_customer_idx ON fintech.account (customer_id);
CREATE TABLE IF NOT EXISTS fintech.transfer (
    transfer_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES fintech.account,
    destination_id bigint NOT NULL REFERENCES fintech.account,
    amount numeric(18,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'),
    booked_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (source_id <> destination_id)
);
CREATE INDEX IF NOT EXISTS transfer_source_idx ON fintech.transfer (source_id);
CREATE INDEX IF NOT EXISTS transfer_destination_idx ON fintech.transfer (destination_id);
COMMIT;
